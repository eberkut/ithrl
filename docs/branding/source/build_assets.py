#!/usr/bin/env python3
"""Rebuild the ithrl artwork from geometry and original font outlines.

Run from the checkout: uv run --group branding python docs/branding/source/build_assets.py
Pass --check to compare generated bytes without writing files. No network operations.
"""

from __future__ import annotations

import argparse
import json
import sys
from html import escape
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from resvg_py import svg_to_bytes

SOURCE = Path(__file__).resolve().parent
BRANDING = SOURCE.parent
CONFIG = json.loads((SOURCE / "geometry.json").read_text())
COLORS = CONFIG["colors"]


def number(value: float) -> str:
    return f"{value:.3f}".rstrip("0").rstrip(".") or "0"


def wordmark_paths() -> list[tuple[str, str]]:
    settings = CONFIG["wordmark"]
    font = TTFont(SOURCE / settings["font"])
    glyphs = font.getGlyphSet()
    bounds = {}
    for name in settings["glyphs"]:
        pen = BoundsPen(glyphs)
        glyphs[name].draw(pen)
        bounds[name] = pen.bounds
    top = max(bounds[n][3] for n in settings["glyphs"])
    scale = settings["visible_height"] / top
    cursor = settings["left"]
    result = []
    for index, (character, name) in enumerate(zip("ithrl", settings["glyphs"], strict=True)):
        left, _, right, _ = bounds[name]
        pen = SVGPathPen(glyphs, ntos=number)
        transform = TransformPen(
            pen, (scale, 0, 0, -scale, cursor - left * scale, settings["baseline"])
        )
        glyphs[name].draw(transform)
        result.append((character, pen.getCommands()))
        cursor += (right - left) * scale
        if index < 4:
            cursor += settings["visible_gaps"][index]
    font.close()
    return result


LETTERS = wordmark_paths()


def mark_body(ink: str, accent: str, adaptive: bool = False) -> str:
    pieces = []
    for part in CONFIG["parts"]:
        is_accent = part.get("accent", False)
        color = accent if is_accent else ink
        css = f' class="{"accent" if is_accent else "ink"}"' if adaptive else ""
        pieces.append(f'<path id="{part["id"]}"{css} fill="{color}" d="{part["d"]}"/>')
    return "\n".join(pieces)


def logo_body(ink: str, accent: str) -> str:
    text = "\n".join(f'<path id="letter-{character}" d="{path}"/>' for character, path in LETTERS)
    return (
        f'<g id="emblem">\n{mark_body(ink, accent)}\n</g>\n'
        f'<g id="wordmark" fill="{ink}" aria-hidden="true">\n{text}\n</g>'
    )


def document(body: str, viewbox: list[int], title: str, description: str, css: str = "") -> str:
    _, _, width, height = viewbox
    view = " ".join(map(str, viewbox))
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
        f'viewBox="{view}" role="img" aria-labelledby="title description">\n'
        f'<title id="title">{escape(title)}</title>\n'
        f'<desc id="description">{escape(description)}</desc>\n'
        "<metadata>ithrl logo 1.0. Hand-refined spear geometry; "
        "Geist Bold outlined wordmark with ss08 i and ss03 l. "
        "See source/OFL-Geist.txt for font provenance.</metadata>\n"
        f"{css}{body}\n</svg>\n"
    )


def outline_label(text: str, x: float, baseline: float, height: float, color: str) -> str:
    """Outline sharing-card labels without depending on installed fonts."""
    font = TTFont(SOURCE / CONFIG["wordmark"]["font"])
    glyphs = font.getGlyphSet()
    cmap = font.getBestCmap()
    scale = height / 1000
    cursor = x
    result = []
    for character in text:
        name = cmap[ord(character)]
        pen = SVGPathPen(glyphs, ntos=number)
        glyphs[name].draw(TransformPen(pen, (scale, 0, 0, -scale, cursor, baseline)))
        if pen.getCommands():
            result.append(f'<path d="{pen.getCommands()}"/>')
        cursor += font["hmtx"][name][0] * scale
    font.close()
    return f'<g fill="{color}">' + "".join(result) + "</g>"


def social_card(width: int, height: int) -> str:
    """Use outlined labels so sharing cards never depend on installed fonts."""
    ink, accent = COLORS["white"], COLORS["dark_accent"]
    logo_width = 640
    body = [
        f'<rect width="{width}" height="{height}" fill="{COLORS["graphite"]}"/>',
        f'<g transform="translate({(width - logo_width) / 2} 42) scale({logo_width / 1040})">'
        + logo_body(ink, accent)
        + "</g>",
    ]
    for text, baseline in (
        ("Find smaller agent contexts", height - 150),
        ("that preserve a selected model behavior", height - 106),
    ):
        body.append(outline_label(text, 116, baseline, 32, ink))
    body.append(outline_label("github.com/eberkut/ithrl", 116, height - 48, 22, "#ABB9B4"))
    return document(
        "\n".join(body),
        [0, 0, width, height],
        "ithrl",
        "Find smaller agent contexts that preserve a selected model behavior.",
    )


def assets() -> dict[Path, bytes]:
    result = {}
    variants = {
        "light": (COLORS["graphite"], COLORS["teal"], "for light backgrounds"),
        "dark": (COLORS["white"], COLORS["dark_accent"], "for dark backgrounds"),
    }
    for suffix, (ink, accent, purpose) in variants.items():
        svg = document(
            logo_body(ink, accent),
            CONFIG["logo_viewbox"],
            "ithrl",
            f"ithrl spear and lowercase wordmark {purpose}.",
        )
        result[BRANDING / f"ithrl-logo-{suffix}.svg"] = svg.encode()

    icon = (
        document(
            mark_body(COLORS["graphite"], COLORS["teal"], adaptive=True),
            CONFIG["mark_viewbox"],
            "ithrl",
            "ithrl spear.",
        )
        .replace('width="512" height="512"', 'width="32" height="32" class="ithrl-mark size-8"')
        .replace(
            'role="img" aria-labelledby="title description"', 'aria-hidden="true" focusable="false"'
        )
    )
    result[BRANDING / "ithrl-icon.svg"] = icon.encode()
    result[BRANDING / "ithrl-logo.png"] = svg_to_bytes(
        svg_string=result[BRANDING / "ithrl-logo-light.svg"].decode(),
        width=640,
        background="#FFFFFF",
        skip_system_fonts=True,
    )

    css = (
        "<style>\n.ink{fill:#202427}.accent{fill:#00A58F}\n"
        "@media (prefers-color-scheme:dark){.ink{fill:#FFFFFF}.accent{fill:#24CDB5}}\n"
        "</style>\n"
    )
    favicon = document(
        mark_body(COLORS["graphite"], COLORS["teal"], adaptive=True),
        CONFIG["mark_viewbox"],
        "ithrl",
        "ithrl spear; adapts to light and dark themes.",
        css,
    )
    result[BRANDING / "ithrl-favicon.svg"] = favicon.encode()
    for destination, width, height in (
        (BRANDING / "social-preview.png", 1280, 640),
        (BRANDING / "ithrl-social.png", 1200, 630),
    ):
        result[destination] = svg_to_bytes(
            svg_string=social_card(width, height), skip_system_fonts=True
        )
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="check generated files without writing"
    )
    args = parser.parse_args()
    mismatches = []
    for path, data in assets().items():
        if args.check:
            if not path.is_file() or path.read_bytes() != data:
                mismatches.append(str(path.relative_to(BRANDING.parent.parent)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    if mismatches:
        sys.stderr.write("Regenerate branding assets:\n" + "\n".join(mismatches) + "\n")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
